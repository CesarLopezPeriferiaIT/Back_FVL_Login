-- Catalogos geograficos de Colombia (divipola DANE): departamento y municipio.
-- Fuente: Tabla-Codigos-Dane.pdf. Idempotente: crea las tablas si faltan e inserta solo los codigos ausentes.
-- Los codigos son VARCHAR para conservar los ceros a la izquierda, como en el PDF.
-- codigo de departamento: 2 digitos DANE ('05').
-- codigo de municipio: codigo DANE completo de 5 digitos (departamento + municipio, '05001'),
-- unico a nivel nacional; el codigo de 3 digitos del PDF se repite entre departamentos.

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

IF OBJECT_ID('dbo.catalogo_departamento', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.catalogo_departamento (
        codigo VARCHAR(2)   NOT NULL,
        nombre NVARCHAR(100) NOT NULL,
        CONSTRAINT PK_catalogo_departamento PRIMARY KEY CLUSTERED (codigo)
    );
END
GO

IF OBJECT_ID('dbo.catalogo_municipio', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.catalogo_municipio (
        codigo              VARCHAR(5)    NOT NULL,
        nombre              NVARCHAR(100) NOT NULL,
        codigo_departamento VARCHAR(2)   NOT NULL,
        CONSTRAINT PK_catalogo_municipio PRIMARY KEY CLUSTERED (codigo),
        CONSTRAINT FK_catalogo_municipio_departamento
            FOREIGN KEY (codigo_departamento) REFERENCES dbo.catalogo_departamento (codigo)
    );
END
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.catalogo_municipio') AND name = 'IX_catalogo_municipio_departamento'
)
BEGIN
    CREATE INDEX IX_catalogo_municipio_departamento ON dbo.catalogo_municipio (codigo_departamento);
END
GO

